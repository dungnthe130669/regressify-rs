import { randomUUID } from "node:crypto";
import { copyFile, lstat, mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { versionBuild } from "./version-assets";

export async function collectFiles(
  directory: string,
  prefix = "",
): Promise<Map<string, Uint8Array>> {
  const files = new Map<string, Uint8Array>();
  for (const entry of (await readdir(directory)).sort()) {
    const path = join(directory, entry);
    const relative = prefix ? `${prefix}/${entry}` : entry;
    const metadata = await lstat(path);
    if (metadata.isSymbolicLink()) throw new Error(`Build output contains a symlink: ${relative}`);
    if (metadata.isDirectory()) {
      for (const [name, bytes] of await collectFiles(path, relative)) files.set(name, bytes);
    } else if (metadata.isFile()) files.set(relative, await readFile(path));
    else throw new Error(`Build output contains a non-regular file: ${relative}`);
  }
  return files;
}

export function validateBuild(files: Map<string, Uint8Array>): void {
  const index = files.get("index.html");
  if (!index || !new TextDecoder().decode(index).includes("__SNAPSHOT_MANIFEST__"))
    throw new Error("Build is missing the snapshot bootstrap.");
  if (!new TextDecoder().decode(index).includes("__SNAPSHOT_TITLE__"))
    throw new Error("Build is missing the title placeholder.");
  for (const name of files.keys()) {
    if (name !== "index.html" && !/^_snapshot\/assets\/[\w.-]+\.(js|css|woff2|png|svg)$/.test(name))
      throw new Error(`Unexpected build artifact: ${name}`);
  }
  for (const extension of [".js", ".css", ".woff2"]) {
    if (![...files.keys()].some((name) => name.endsWith(extension)))
      throw new Error(`Build is missing ${extension} assets.`);
  }
  if ([...files.keys()].filter((name) => name.endsWith(".js")).length !== 1)
    throw new Error("Snapshot assets must use one self-contained JavaScript bundle.");
}

export async function syncAssets(
  dist: string,
  hosting: string,
  destination: string,
): Promise<void> {
  const input = await collectFiles(dist);
  validateBuild(input);
  const files = versionBuild(input);
  for (const name of ["_headers", "_redirects", "staticwebapp.config.json", "gitignore"])
    files.set(name, await readFile(join(hosting, name)));
  const entries = [...files.keys()].filter((name) => name !== "index.html").sort();
  files.set(
    "assets.rs",
    new TextEncoder().encode(
      `// Generated by frontend/scripts/sync-assets.ts.\npub const FRONTEND_FILES: &[(&str, &[u8])] = &[\n${entries.map((name) => `    (${JSON.stringify(name)}, include_bytes!(${JSON.stringify(name)})),`).join("\n")}\n];\n`,
    ),
  );
  const metadata = await lstat(destination).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (metadata && (!metadata.isDirectory() || metadata.isSymbolicLink()))
    throw new Error("Asset destination must be a real directory.");
  const previous = metadata ? await collectFiles(destination) : new Map<string, Uint8Array>();
  const staging = `${destination}.next-${randomUUID()}`;
  await mkdir(staging, { recursive: false });
  try {
    for (const [name, bytes] of files) {
      const output = join(staging, name);
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, bytes);
    }
    await mkdir(destination, { recursive: true });
    // Windows directory watchers can deny directory renames; publish complete files instead.
    const order = [...files.keys()].filter((name) => name !== "index.html" && name !== "assets.rs");
    order.push("index.html", "assets.rs");
    for (const name of order) {
      const bytes = files.get(name);
      if (!bytes) throw new Error(`Missing generated asset: ${name}`);
      const existing = previous.get(name);
      if (existing && Buffer.from(existing).equals(bytes)) continue;
      const target = join(destination, name);
      await mkdir(dirname(target), { recursive: true });
      const temporary = `${target}.${randomUUID()}.tmp`;
      try {
        await copyFile(join(staging, name), temporary);
        await rename(temporary, target);
      } finally {
        await rm(temporary, { force: true });
      }
    }
    for (const name of previous.keys()) {
      if (!files.has(name)) await rm(join(destination, name));
    }
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const frontend = resolve(import.meta.dir, "..");
  await syncAssets(
    join(frontend, "dist"),
    join(frontend, "hosting"),
    resolve(frontend, "../src/snapshot/data"),
  );
  console.log("Synchronized stable snapshot assets with versioned URLs to src/snapshot/data.");
}
